import { describe, expect, it } from "vitest";
import { buildManifest, buildManifestFromChecksums, classify, isValidAssetName, isValidTag, parseChecksums, parseTagFromLocation } from "../src/lib";

describe("tag / asset validation", () => {
  it("accepts semantic version tags only", () => {
    expect(isValidTag("v1.3.293")).toBe(true);
    expect(isValidTag("1.3.293")).toBe(false);
    expect(isValidTag("v1.3")).toBe(false);
    expect(isValidTag("v1.3.293-beta")).toBe(false);
    expect(isValidTag(null)).toBe(false);
  });

  it("rejects asset names that could escape the release path", () => {
    expect(isValidAssetName("ggcode_linux_x86_64.tar.gz")).toBe(true);
    expect(isValidAssetName("checksums.txt")).toBe(true);
    expect(isValidAssetName("../../etc/passwd")).toBe(false);
    expect(isValidAssetName("a/b")).toBe(false);
    expect(isValidAssetName("a%2Fb")).toBe(false);
    expect(isValidAssetName("")).toBe(false);
    expect(isValidAssetName(".hidden")).toBe(false);
  });

  it("extracts the tag from the releases/latest redirect", () => {
    expect(parseTagFromLocation("https://github.com/topcheer/ggcode/releases/tag/v1.3.293")).toBe("v1.3.293");
    expect(parseTagFromLocation("https://github.com/topcheer/ggcode/releases/tag/v1.3.293?x=1")).toBe("v1.3.293");
    expect(parseTagFromLocation("https://github.com/topcheer/ggcode/releases/tag/nightly")).toBeNull();
    expect(parseTagFromLocation("")).toBeNull();
  });
});

describe("routing", () => {
  it("classifies the documented paths", () => {
    expect(classify("/healthz")).toEqual({ kind: "health" });
    expect(classify("/")).toEqual({ kind: "index" });
    expect(classify("/latest/manifest.json")).toEqual({ kind: "latest", rest: "/manifest.json" });
    expect(classify("/latest/ggcode_linux_x86_64.tar.gz")).toEqual({ kind: "latest", rest: "/ggcode_linux_x86_64.tar.gz" });
    expect(classify("/v1.3.293/checksums.txt")).toEqual({ kind: "versioned", tag: "v1.3.293", rest: "/checksums.txt" });
    expect(classify("/v1.3.293")).toEqual({ kind: "versioned", tag: "v1.3.293", rest: "" });
    expect(classify("/v1.3")).toEqual({ kind: "not-found" });
    expect(classify("/some/other/repo/file")).toEqual({ kind: "not-found" });
  });
});

describe("manifest", () => {
  it("keeps the publish-site-branch shape and points URLs at the mirror", () => {
    const m = buildManifest(
      "v1.3.293",
      [
        { name: "checksums.txt", size: 10, browser_download_url: "https://github.com/topcheer/ggcode/releases/download/v1.3.293/checksums.txt" },
        { name: "ggcode_linux_x86_64.tar.gz", size: 20, browser_download_url: "https://github.com/topcheer/ggcode/releases/download/v1.3.293/ggcode_linux_x86_64.tar.gz" },
        { name: "../evil", size: 1, browser_download_url: "x" },
      ],
      "https://download.ggcode.dev"
    );
    expect(m.version).toBe("v1.3.293");
    expect(m.source).toBe("v1.3.293");
    expect(m.files.map((f) => f.name)).toEqual(["checksums.txt", "ggcode_linux_x86_64.tar.gz"]);
    expect(m.files[1].url).toBe("https://download.ggcode.dev/v1.3.293/ggcode_linux_x86_64.tar.gz");
    expect(m.files[1].github_url).toContain("github.com/topcheer/ggcode/releases/download/v1.3.293/");
  });
  it("builds an API-free manifest from checksums.txt (the deploy path)", () => {
    const text = [
      "# generated by goreleaser",
      "f344d13d10bff1f572c3b5ebc768faf378410cbf834e30bb4f145d81503daddd  ggcode-1.3.293-1.aarch64.rpm",
      "ED049D5E8587F37D66133CDE4905434DF9B19EE8AB8008C26EEB0D74642FE364 *ggcode_linux_x86_64.tar.gz",
      "not-a-line",
    ].join("\n");
    const entries = parseChecksums(text);
    expect(entries.map((e) => e.name)).toEqual(["ggcode-1.3.293-1.aarch64.rpm", "ggcode_linux_x86_64.tar.gz"]);
    expect(entries[1].sha256).toBe("ed049d5e8587f37d66133cde4905434df9b19ee8ab8008c26eeb0d74642fe364");
    const m = buildManifestFromChecksums("v1.3.293", entries, "https://download.ggcode.dev");
    expect(m.version).toBe("v1.3.293");
    expect(m.files.map((f) => f.name).sort()).toEqual(["ggcode-1.3.293-1.aarch64.rpm", "ggcode_linux_x86_64.tar.gz"].sort());
    const tgz = m.files.find((f) => f.name === "ggcode_linux_x86_64.tar.gz")!;
    expect(tgz.url).toBe("https://download.ggcode.dev/v1.3.293/ggcode_linux_x86_64.tar.gz");
    expect(tgz.github_url).toBe("https://github.com/topcheer/ggcode/releases/download/v1.3.293/ggcode_linux_x86_64.tar.gz");
    expect(m.files.every((f) => f.sha256!.length === 64)).toBe(true);
  });
});
