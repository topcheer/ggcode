#!/bin/bash
# ggcode container entrypoint
# Default: --plain mode; any args pass through (daemon, prompts, flags).
#
# Startup hooks (idempotent, each guarded):
#   1. Custom CA certs   - mount dir at /certs (or GGCODE_CA_DIR); certs are
#                          installed into the system trust store and exported
#                          to every language stack via env vars.
#   2. Registry mirrors  - enterprise artifact repositories via env vars
#                          (PIP_INDEX_URL, NPM_CONFIG_REGISTRY, GOPROXY, ...)
#   3. Model config      - GGCODE_ENDPOINT/API_KEY/MODEL -> ~/.ggcode/config.yaml
set -e

# ---------- 1. custom CA certificates ----------
CA_DIR="${GGCODE_CA_DIR:-/certs}"
if [ -d "$CA_DIR" ] && ls "$CA_DIR"/*.crt "$CA_DIR"/*.pem "$CA_DIR"/*.cer >/dev/null 2>&1; then
  TRUST_STAMP="$HOME/.ggcode/.ca-trust-stamp"
  # re-run only when the cert set changed (cheap fingerprint)
  FP=$(ls -la "$CA_DIR" 2>/dev/null | md5sum | cut -d' ' -f1)
  if [ "$FP" != "$(cat "$TRUST_STAMP" 2>/dev/null || true)" ]; then
    sudo mkdir -p /usr/local/share/ca-certificates/ggcode-custom
    sudo cp "$CA_DIR"/*.crt "$CA_DIR"/*.pem "$CA_DIR"/*.cer \
         /usr/local/share/ca-certificates/ggcode-custom/ 2>/dev/null || true
    sudo update-ca-certificates --fresh >/dev/null 2>&1 || true
    echo "$FP" > "$(dirname "$TRUST_STAMP")/.ca-trust-stamp.tmp" && \
      mkdir -p "$(dirname "$TRUST_STAMP")" && mv "$(dirname "$TRUST_STAMP")/.ca-trust-stamp.tmp" "$TRUST_STAMP"
  fi
  # aggregate bundle + per-language exports
  BUNDLE="$HOME/.ggcode/ca-bundle.crt"
  cat /etc/ssl/certs/ca-certificates.crt "$CA_DIR"/*.crt "$CA_DIR"/*.pem "$CA_DIR"/*.cer > "$BUNDLE" 2>/dev/null || true
  export SSL_CERT_FILE="$BUNDLE"                    # curl / openssl / go
  export REQUESTS_CA_BUNDLE="$BUNDLE"               # python requests
  export NODE_EXTRA_CA_CERTS="$BUNDLE"              # node/npm/pnpm/yarn
  export GIT_SSL_CAINFO="$BUNDLE"                   # git against private registries
  export DOTNET_ROOT_CERTIFICATES="$(ls "$CA_DIR"/*.crt "$CA_DIR"/*.pem 2>/dev/null | tr '\n' ':')"
  export JAVA_TOOL_OPTIONS="${JAVA_TOOL_OPTIONS:+$JAVA_TOOL_OPTIONS }-Djavax.net.ssl.trustStore=/etc/ssl/certs/java/cacerts"
fi

# ---------- 2. enterprise artifact registries ----------
# (env vars consumed natively where possible; file-based managers get configs)
if [ -n "$MAVEN_MIRROR_URL" ]; then
  mkdir -p "$HOME/.m2"
  cat > "$HOME/.m2/settings.xml" <<EOF
<settings>
  <mirrors>
    <mirror>
      <id>internal</id><mirrorOf>*</mirrorOf>
      <url>${MAVEN_MIRROR_URL}</url>
    </mirror>
  </mirrors>
</settings>
EOF
fi
if [ -n "$GRADLE_REPO_URL" ]; then
  mkdir -p "$HOME/.gradle"
  cat > "$HOME/.gradle/init.gradle" <<EOF
allprojects {
  repositories {
    maven { url "${GRADLE_REPO_URL}" }
  }
}
settingsEvaluated { it.repositories { maven { url "${GRADLE_REPO_URL}" } } }
EOF
fi
if [ -n "$CARGO_REGISTRIES_CRATE_IO_INDEX" ]; then
  mkdir -p "$HOME/.cargo"
  cat > "$HOME/.cargo/config.toml" <<EOF
[source.crates-io]
replace-with = "internal"
[source.internal]
registry = "${CARGO_REGISTRIES_CRATE_IO_INDEX}"
EOF
fi
if [ -n "$GEM_MIRROR_URL" ]; then
  cat > "$HOME/.gemrc" <<EOF
---
:sources:
  - ${GEM_MIRROR_URL}
EOF
fi
# npm: NPM_CONFIG_REGISTRY is consumed natively by npm/pnpm/yarn
# pip: PIP_INDEX_URL consumed natively
# go:  GOPROXY/GOPRIVATE consumed natively
# dotnet: DOTNET_NUGET_SOURCE -> nuget.config
if [ -n "$DOTNET_NUGET_SOURCE" ]; then
  cat > "$HOME/nuget.config" <<EOF
<?xml version="1.0"?>
<packageSources>
  <clear />
  <add key="internal" value="${DOTNET_NUGET_SOURCE}" />
</packageSources>
EOF
fi

# ---------- 3. first-run model config ----------
if [ ! -f "$HOME/.ggcode/config.yaml" ] && [ -n "$GGCODE_ENDPOINT$GGCODE_API_KEY" ]; then
  mkdir -p "$HOME/.ggcode"
  umask 077
  cat > "$HOME/.ggcode/config.yaml" <<EOF
# generated by container entrypoint from environment
endpoint: ${GGCODE_ENDPOINT:-}
model: ${GGCODE_MODEL:-}
api_key: ${GGCODE_API_KEY:-}
EOF
fi

# ---------- run ----------
if [ $# -eq 0 ]; then
  exec ggcode --plain
else
  exec ggcode "$@"
fi
