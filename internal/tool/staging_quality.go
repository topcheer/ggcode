func AnalyzeStagingQuality(diffOutput string) string {
	if strings.TrimSpace(diffOutput) == "" {
		return ""
	}

	fileSet := make(map[string]bool)
	for _, line := range strings.Split(diffOutput, "\n") {
		if m := diffFileHeader.FindStringSubmatch(line); m != nil {
			fileSet[diffHeaderPath(m)] = true
		} else if m := diffGitHeader.FindStringSubmatch(line); m != nil {

			path := m[1]
			if path == "" {
				path = m[2]
			}
			fileSet[normalizeGitDiffPath(path)] = true
		}
	}

	if len(fileSet) == 0 {
		return ""
	}

	var issues []StagingIssue
	for path := range fileSet {
		issues = append(issues, checkStagingFile(path)...)
	}

	if len(issues) == 0 {
		return ""
	}

	return formatStagingIssues(issues)
}

func checkStagingFile(path string) []StagingIssue {
	var issues []StagingIssue
	lower := strings.ToLower(path)
	base := filepath.Base(path)

	if reason, ok := osArtifactFiles[strings.ToLower(base)]; ok {
		issues = append(issues, StagingIssue{
			Path: path, Category: "os-artifact", Reason: reason,
		})
	}

	for pattern, reason := range ideArtifactFiles {
		if stagingPatternMatch(lower, pattern) {
			issues = append(issues, StagingIssue{
				Path: path, Category: "ide-artifact", Reason: reason,
			})
			break
		}
	}

	for _, d := range buildArtifactDirs {
		if hasPathPrefixSegment(lower, d.prefix) {
			issues = append(issues, StagingIssue{
				Path: path, Category: "build-artifact", Reason: d.reason,
			})
			break
		}
	}

	for _, d := range vendoredDirs {
		if hasPathPrefixSegment(lower, d.prefix) {
			issues = append(issues, StagingIssue{
				Path: path, Category: "vendored", Reason: d.reason,
			})
			break
		}
	}

	nameLower := filepath.Base(lower)
	for _, p := range generatedFilePatterns {
		pl := strings.ToLower(p.pattern)
		var matched bool
		if strings.HasPrefix(pl, ".") || strings.HasPrefix(pl, "_") {
			matched = strings.HasSuffix(nameLower, pl)
		} else {
			matched = nameLower == pl
		}
		if matched {
			issues = append(issues, StagingIssue{
				Path: path, Category: "generated", Reason: p.reason,
			})
			break
		}
	}

	for _, ext := range binaryExtensions {
		if strings.HasSuffix(lower, ext) {
			issues = append(issues, StagingIssue{
				Path: path, Category: "binary", Reason: "compiled binary file",
			})
			break
		}
	}

	if len(issues) > 1 {
		issues = issues[:1]
	}

	return issues
}

func stagingPatternMatch(path, pattern string) bool {
	if strings.Contains(pattern, "*") {
		matched, err := filepath.Match(pattern, filepath.Base(path))
		if err == nil && matched {
			return true
		}

		matched, err = filepath.Match(pattern, path)
		if err == nil && matched {
			return true
		}
		return false
	}

	if strings.Contains(pattern, "/") {
		if strings.HasSuffix(pattern, "/") {
			return "/"+path+"/" == pattern || strings.Contains("/"+path+"/", "/"+pattern)
		}
		return path == pattern || strings.HasSuffix(path, "/"+pattern)
	}

	if strings.HasPrefix(pattern, ".") {
		for _, seg := range strings.Split(path, "/") {
			if seg == pattern {
				return true
			}
		}
		return false
	}
	return filepath.Base(path) == pattern
}

var diffGitHeader = regexp.MustCompile(`^diff --git (?:a/\S+ |"a/[^"]+" )(?:b/(\S+)|"b/([^"]+)")`)

func normalizeGitDiffPath(s string) string {
	s = strings.Trim(s, `"`)
	return gitUnquotePath(s)
}

func formatStagingIssues(issues []StagingIssue) string {
	if len(issues) == 0 {
		return ""
	}

	var b strings.Builder
	b.WriteString("Warning: the following staged files are likely auto-generated or " +
		"should not be committed:\n\n")

	shown := issues
	if len(shown) > maxStagingWarnings {
		shown = shown[:maxStagingWarnings]
	}

	for _, iss := range shown {
		b.WriteString(fmt.Sprintf("  - %s (%s): %s\n", iss.Path, iss.Category, iss.Reason))
	}

	if len(issues) > maxStagingWarnings {
		b.WriteString(fmt.Sprintf("  ... and %d more\n", len(issues)-maxStagingWarnings))
	}

	b.WriteString("\nConsider removing these files from staging with 'git restore --staged <file>' " +
		"and adding them to .gitignore if not already present.")

	return b.String()
}

func hasPathPrefixSegment(path, prefix string) bool {
	for i := 0; i < len(path); i++ {
		if i > 0 && path[i-1] != '/' {
			continue
		}
		if !strings.HasPrefix(path[i:], prefix) {
			continue
		}

		if strings.HasSuffix(prefix, "/") {
			return true
		}
		end := i + len(prefix)
		if end == len(path) || path[end] == '/' {
			return true
		}
	}
	return false
}
