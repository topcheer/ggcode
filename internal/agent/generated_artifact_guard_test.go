func TestGeneratedArtifactState_CaseInsensitivePath(t *testing.T) {
	g := newGeneratedArtifactState()

	// Lock file with uppercase letters in path
	hint := g.checkGeneratedArtifact("/Project/GO.SUM")
	// Should NOT match because lockFileSuggestions uses lowercase base name
	// The function lowercases the path, so it should match
	if hint == "" {
		// "GO.SUM" lowercased to "go.sum" should match
		t.Error("expected warning for GO.SUM (case-insensitive)")
	}
}

