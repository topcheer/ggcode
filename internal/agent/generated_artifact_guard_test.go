func TestGeneratedArtifactState_LockFile(t *testing.T) {
	g := newGeneratedArtifactState()

	hint := g.checkGeneratedArtifact("/project/go.sum")
	if hint == "" {
		t.Fatal("expected warning for go.sum")
	}
	if !contains(hint, "go mod tidy") {
		t.Errorf("expected 'go mod tidy' suggestion, got: %s", hint)
	}
	if !contains(hint, "lock file") {
		t.Errorf("expected 'lock file' mention, got: %s", hint)
	}
}

