func TestGeneratedArtifactState_DoNotEditHeader(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "generated_code.go")
	content := "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage main\n"
	if err := os.WriteFile(path, []byte(content), 0644); err != nil {
		t.Fatal(err)
	}

	g := newGeneratedArtifactState()
	hint := g.checkGeneratedArtifact(path)
	if hint == "" {
		t.Fatal("expected warning for DO NOT EDIT file")
	}
	if !contains(hint, "DO NOT EDIT") {
		t.Errorf("expected DO NOT EDIT mention, got: %s", hint)
	}
}

