func TestGeneratedArtifactState_FiresOncePerFile(t *testing.T) {
	g := newGeneratedArtifactState()

	hint1 := g.checkGeneratedArtifact("/project/go.sum")
	if hint1 == "" {
		t.Fatal("expected first warning")
	}

	hint2 := g.checkGeneratedArtifact("/project/go.sum")
	if hint2 != "" {
		t.Error("expected no duplicate warning for same file")
	}
}

func TestGeneratedArtifactState_ResetClearsWarning(t *testing.T) {
	g := newGeneratedArtifactState()

	hint1 := g.checkGeneratedArtifact("/project/go.sum")
	if hint1 == "" {
		t.Fatal("expected first warning")
	}

	g.reset()

	hint2 := g.checkGeneratedArtifact("/project/go.sum")
	if hint2 == "" {
		t.Fatal("expected warning after reset")
	}
}

