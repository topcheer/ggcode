func TestCheckMissingTestCompanion_ExistingFileNewExportedFunc(t *testing.T) {
	dir := t.TempDir()

	old := `package mypkg

func Existing() int { return 0 }
`

	newSrc := `package mypkg

func Existing() int { return 0 }

func NewFeature(x int) int {
	return x * 2
}
`
	warning := checkMissingTestCompanion(filepath.Join(dir, "feature.go"), old, newSrc)
	if warning == "" {
		t.Errorf("expected warning for new exported func without test companion")
	}
	if !strings.Contains(warning, "NewFeature") {
		t.Errorf("warning should mention NewFeature, got: %s", warning)
	}
}

