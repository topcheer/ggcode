func TestCheckMissingTestCompanion_NewFileWithTests(t *testing.T) {
	dir := t.TempDir()
	testFile := filepath.Join(dir, "existing_test.go")
	if err := os.WriteFile(testFile, []byte("package mypkg\n"), 0644); err != nil {
		t.Fatal(err)
	}

	src := `package mypkg

func Process(s string) string {
	return s + "!"
}

func Validate(n int) bool {
	return n > 0
}
`
	warning := checkMissingTestCompanion(filepath.Join(dir, "process.go"), "", src)
	if warning != "" {
		t.Errorf("expected no warning when test file exists, got: %s", warning)
	}
}

