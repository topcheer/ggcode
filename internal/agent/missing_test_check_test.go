func TestFindExportedFuncs(t *testing.T) {
	// nil ast
	got := findExportedFuncs(nil)
	if got != nil {
		t.Errorf("expected nil for nil ast, got %v", got)
	}

	// mixed exported and unexported
	src := `package p
func Exported() {}
func unexported() {}
func TestX(t *testing.T) {}
func init() {}
`
	fset := token.NewFileSet()
	astFile, err := parser.ParseFile(fset, "", src, 0)
	if err != nil {
		t.Fatal(err)
	}
	got = findExportedFuncs(astFile)
	if len(got) != 1 || got[0] != "Exported" {
		t.Errorf("expected [Exported], got %v", got)
	}
}

