func TestSpecToTasks_BasicConversion(t *testing.T) {
	spec := `# Feature

## Requirements

### REQ-1: Login page
- Acceptance: Form validates
Description.

### REQ-2: Dashboard
- Acceptance: Shows user info
- Depends on: REQ-1
`
	doc := ParseSpec(spec)
	tasks, reqMap := SpecToTasks(doc, SpecToTasksOptions{
		EntryPoint: "harness",
	})

	if len(tasks) != 2 {
		t.Fatalf("expected 2 tasks, got %d", len(tasks))
	}
	if tasks[0].SpecRef != "REQ-1" {
		t.Errorf("task[0] SpecRef = %q, want REQ-1", tasks[0].SpecRef)
	}
	if tasks[1].SpecRef != "REQ-2" {
		t.Errorf("task[1] SpecRef = %q, want REQ-2", tasks[1].SpecRef)
	}
	// Check dependency mapping: REQ-2 depends on REQ-1 → task[1] depends on task[0]
	if len(tasks[1].DependsOn) != 1 {
		t.Fatalf("task[1] DependsOn = %v, want 1 dep", tasks[1].DependsOn)
	}
	if tasks[1].DependsOn[0] != tasks[0].ID {
		t.Errorf("task[1] DependsOn[0] = %q, want task[0].ID = %q", tasks[1].DependsOn[0], tasks[0].ID)
	}
	// Check reqMap
	if reqMap["REQ-1"] != tasks[0].ID {
		t.Errorf("reqMap[REQ-1] = %q", reqMap["REQ-1"])
	}
	// Check acceptance criteria preserved
	if len(tasks[0].AcceptanceCriteria) != 1 {
		t.Errorf("task[0] acceptance criteria = %v", tasks[0].AcceptanceCriteria)
	}
}

func TestSpecToTasks_SequentialChain(t *testing.T) {
	spec := `# Feature

## Requirements

### REQ-1: A
### REQ-2: B
### REQ-3: C
`
	doc := ParseSpec(spec)
	tasks, _ := SpecToTasks(doc, SpecToTasksOptions{
		SequentialChain: true,
	})

	if len(tasks) != 3 {
		t.Fatalf("expected 3 tasks, got %d", len(tasks))
	}
	// task[0] should have no deps
	if len(tasks[0].DependsOn) != 0 {
		t.Errorf("task[0] should have no deps, got %v", tasks[0].DependsOn)
	}
	// task[1] depends on task[0]
	if len(tasks[1].DependsOn) != 1 || tasks[1].DependsOn[0] != tasks[0].ID {
		t.Errorf("task[1] deps = %v", tasks[1].DependsOn)
	}
	// task[2] depends on task[1]
	if len(tasks[2].DependsOn) != 1 || tasks[2].DependsOn[0] != tasks[1].ID {
		t.Errorf("task[2] deps = %v", tasks[2].DependsOn)
	}
}

