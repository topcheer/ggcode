func TestParseSpec_InlineAcceptanceCriteria(t *testing.T) {
	spec := `# Test

## Requirements

### REQ-1: Feature
Acceptance: Must validate
Priority: high
Depends on: REQ-0
`
	req := parseSingleReq(t, spec)
	// These are inline (non-bullet) forms with key: value
	if req.Priority != "high" {
		t.Errorf("Priority = %q", req.Priority)
	}
	// Note: "Acceptance: Must validate" as a non-bullet line has key="acceptance"
	// and value="Must validate" — should be captured
	found := false
	for _, ac := range req.AcceptanceCriteria {
		if strings.Contains(ac, "Must validate") {
			found = true
		}
	}
	if !found {
		t.Errorf("expected acceptance criteria from inline, got %v", req.AcceptanceCriteria)
	}
}
